public class Loops {
    public static void main(String[] args) {
        for (int i=1; i<=5; i++){
            System.out.println(i);
        }
        int j=1;
        while (j<=5){
            System.out.println("Hello");
            j++;
        }
        for (int k=10; k>=1;k--){
            System.out.println(k);
        }
    }
}
